#!/usr/bin/env python3
"""Copies the icons of web/src/components/Icons.tsx into assets/icons/*.svg
and writes src/icons_generated.rs, so the native client draws the very same
outlines. Run from anywhere: python3 desktop/ui/scripts/icons.py
"""

import pathlib
import re

HERE = pathlib.Path(__file__).resolve().parent
UI = HERE.parent
SOURCE = UI.parent.parent / "web" / "src" / "components" / "Icons.tsx"
ASSETS = UI / "assets" / "icons"
GENERATED = UI / "src" / "icons_generated.rs"

FUNCTION = re.compile(
    r"export function (\w+)Icon\(props: IconProps\) \{\s*return \(\s*<svg \{\.\.\.base\(props\)\}>(.*?)</svg>",
    re.S,
)
ELEMENT = re.compile(r"<(path|circle|rect)\s([^>]*?)\s*/>", re.S)


def kebab(name: str) -> str:
    return re.sub(r"(?<!^)(?=[A-Z])", "-", name).lower()


def main() -> None:
    text = SOURCE.read_text(encoding="utf-8")
    icons = FUNCTION.findall(text)
    if not icons:
        raise SystemExit(f"no icons found in {SOURCE}")
    ASSETS.mkdir(parents=True, exist_ok=True)
    for old in ASSETS.glob("*.svg"):
        old.unlink()
    names = []
    for name, body in icons:
        elements = []
        for tag, attrs in ELEMENT.findall(body):
            # White strokes, tinted when drawn; `currentColor` fills too.
            attrs = attrs.replace('"currentColor"', '"#ffffff"')
            elements.append(f"  <{tag} {' '.join(attrs.split())}/>")
        svg = (
            '<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" '
            'viewBox="0 0 24 24" fill="none" stroke="#ffffff" stroke-width="2" '
            'stroke-linecap="round" stroke-linejoin="round">\n'
            + "\n".join(elements)
            + "\n</svg>\n"
        )
        (ASSETS / f"{kebab(name)}.svg").write_text(svg, encoding="utf-8")
        names.append(name)

    lines = [
        "// Generated by desktop/ui/scripts/icons.py from web/src/components/Icons.tsx.",
        "// Do not edit; run the script again after changing the web icons.",
        "",
        "/// Every icon of the web client (`<Name>Icon` in Icons.tsx).",
        "#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]",
        "pub enum Icon {",
    ]
    lines += [f"    {n}," for n in names]
    lines += [
        "}",
        "",
        "impl Icon {",
        f"    pub const ALL: [Icon; {len(names)}] = [",
    ]
    lines += [f"        Icon::{n}," for n in names]
    lines += [
        "    ];",
        "",
        "    /// The SVG source, drawn in white so a tint gives it its colour.",
        "    pub fn svg(self) -> &'static [u8] {",
        "        match self {",
    ]
    lines += [
        f'            Icon::{n} => include_bytes!("../assets/icons/{kebab(n)}.svg"),'
        for n in names
    ]
    lines += ["        }", "    }", "}", ""]
    GENERATED.write_text("\n".join(lines), encoding="utf-8")
    print(f"{len(names)} icons -> {ASSETS}")


if __name__ == "__main__":
    main()
