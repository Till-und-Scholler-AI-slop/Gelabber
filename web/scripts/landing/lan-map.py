# The landing page's made-up strategy map (public/images/landing/lan-map.svg),
# shown on a monitor as a demo Live. Deterministic: run it again to get the
# same file. Usage, in web/: python3 scripts/landing/lan-map.py
import random, math
random.seed(11)
W,H=40,25
# smooth value noise
def grid(n,m,s):
    return [[random.random() for _ in range(m)] for _ in range(n)]
g=grid(8,6,0)
def noise(x,y):
    fx=x/W*7; fy=y/H*5
    x0=int(fx); y0=int(fy); tx=fx-x0; ty=fy-y0
    s=lambda t:t*t*(3-2*t)
    a=g[x0][y0];b=g[x0+1][y0];c=g[x0][y0+1];d=g[x0+1][y0+1]
    return (a*(1-s(tx))+b*s(tx))*(1-s(ty))+(c*(1-s(tx))+d*s(tx))*s(ty)
h=[[noise(x,y)+0.35*(x/W)-0.18 for y in range(H)] for x in range(W)]
C={'dw':'#1d4560','w':'#2a6684','s':'#cfb57e','g':'#4d8639','G':'#3f7430','f':'#2a5528','p':'#9c7c52','c':'#7d8388','r':'#f3b752','u':'#ff7b5c','v':'#7fb2e5','R':'#5a3b22'}
t=[[None]*H for _ in range(W)]
for x in range(W):
    for y in range(H):
        v=h[x][y]
        if v<0.28: k='dw'
        elif v<0.38: k='w'
        elif v<0.43: k='s'
        elif v<0.62: k='g' if (x+y)%3 else 'G'
        else: k='f' if random.random()<0.75 else 'G'
        t[x][y]=k
# road from (14,12) to (38,6)
x,y=12,14
while x<39:
    if t[x][y] not in ('dw','w'): t[x][y]='p'
    if random.random()<0.25 and y>4: y-=1
    else: x+=1
# castle at 30..33, 8..11 on land
for cx in range(29,33):
    for cy in range(9,12):
        t[cx][cy]='c'
for cx in range(29,33): t[cx][8]='r'
t[29][7]='r'; t[32][7]='r'
t[30][11]='R'; t[31][11]='R'
# units
for (ux,uy,k) in [(25,17,'u'),(27,16,'u'),(26,19,'u'),(35,14,'v'),(36,15,'v')]:
    t[ux][uy]=k
rects=[]
for y in range(H):
    x=0
    while x<W:
        k=t[x][y]; x2=x
        while x2+1<W and t[x2+1][y]==k: x2+=1
        rects.append(f'<rect x="{x}" y="{y}" width="{x2-x+1}" height="1" fill="{C[k]}"/>')
        x=x2+1
svg=f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W} {H}" width="{W*32}" height="{H*32}" shape-rendering="crispEdges">\n<!-- Gelabber landing page: a made-up strategy map for a demo Live. Generated by web/scripts/landing/lan-map.py; not a real game. -->\n'+'\n'.join(rects)+'\n<rect x="24.5" y="15.5" width="4" height="4.4" fill="none" stroke="#f3b752" stroke-width=".18" stroke-dasharray=".6 .3"/>\n</svg>\n'
open('public/images/landing/lan-map.svg','w').write(svg)
print(len(rects))
